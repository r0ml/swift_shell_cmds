/// Serialized: `run` changes PATH for the whole process.
@Suite("what", .serialized) final class whatTest : ShellTest {
  let cmd = "what"
  let suiteBundle = "shell_cmds_whatTest"

  @Test(arguments: whatRecordedResults)
  func matchesTheSystem(_ recorded: ([String], Int, [UInt8], String)) async throws {
    let (args, status, output, error) = recorded
    let fixtures = WhatFixtures()
    defer { fixtures.remove() }
    try await run(withStdin: "", status: status, output: output, error: error, args: args, cd: FilePath(fixtures.root))
  }

  @Test(arguments: whatRecordedInputs)
  func matchesTheSystemOnInput(_ recorded: ([String], [UInt8], Int, [UInt8])) async throws {
    let (args, input, status, output) = recorded
    try await run(withStdin: input, status: status, output: output, error: "", args: args)
  }

  @Test func usageErrors() async throws {
    try await run(withStdin: "", status: 1, output: "", error: "what: illegal option -- x\nusage: what [-qs] [file ...]\n", args: "-x")
