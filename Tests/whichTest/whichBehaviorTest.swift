/// Directories with programs in them (and things that aren't).
final class WhichFixtures {
  let root: String

  init() {
    var template = Array("/tmp/whichtestXXXXXX".utf8CString)
    root = template.withUnsafeMutableBufferPointer { String(cString: mkdtemp($0.baseAddress!)) }
    for dir in ["b1", "b2", "b3", "with space", "b1/adir"] {
      mkdir(root + "/" + dir, 0o755)
    }
    file("b1/tool", 0o755)
    file("b2/tool", 0o755)
    file("b1/noexec", 0o644)
    file("b2/onlyb2", 0o755)
    file("here", 0o755)
    file("with space/spaced", 0o755)
    file("b3/ls", 0o755)
    symlink("tool", root + "/b1/link")
    symlink("nowhere", root + "/b1/dangling")
  }

  func file(_ name: String, _ mode: mode_t) {
    let fd = open(root + "/" + name, O_CREAT | O_WRONLY | O_TRUNC, 0o644)
    _ = "#!/bin/sh\n".withCString { write(fd, $0, strlen($0)) }
    close(fd)
    chmod(root + "/" + name, mode)
  }

  func remove() {
    for name in ["b1/tool", "b2/tool", "b1/noexec", "b2/onlyb2", "here", "with space/spaced", "b3/ls", "b1/link", "b1/dangling"] {
      unlink(root + "/" + name)
    }
    for dir in ["b1/adir", "b1", "b2", "b3", "with space"] {
      rmdir(root + "/" + dir)
    }
    rmdir(root)
  }
}

@Suite("which behavior", .serialized) final class whichBehaviorTest : ShellTest {
  let cmd = "which"
  let suiteBundle = "shell_cmds_whichTest"

  @Test(arguments: whichRecordedResults)
  func matchesTheSystem(_ recorded: (String, [String], Int, String, String)) async throws {
    let (path, args, status, output, error) = recorded
    let fixtures = WhichFixtures()
    defer { fixtures.remove() }
    try await run(withStdin: "", status: status, output: output, error: error, args: args, env: ["PATH": path], cd: FilePath(fixtures.root))
  }

  /// A name that is too long for a file name is not found (and is not an error of another kind).
  @Test func nameTooLong() async throws {
    let fixtures = WhichFixtures()
    defer { fixtures.remove() }
    try await run(withStdin: "", status: 1, output: "", error: "", args: String(repeating: "a", count: 1024), env: ["PATH": "b1"], cd: FilePath(fixtures.root))
    try await run(withStdin: "", status: 1, output: "", error: "", args: String(repeating: "a", count: 1023), env: ["PATH": "b1"], cd: FilePath(fixtures.root))
  }

  /// A name that makes a path too long for the system to take is passed over, and the others are looked at.
  @Test func pathTooLong() async throws {
    let fixtures = WhichFixtures()
    defer { fixtures.remove() }
    let directory = String(repeating: "d", count: 1020)
    try await run(withStdin: "", output: "b1/tool\n", error: "", args: "tool", env: ["PATH": "\(directory):b1"], cd: FilePath(fixtures.root))
  }

  @Test func successOnlyIfAllAreFound() async throws {
    let fixtures = WhichFixtures()
    defer { fixtures.remove() }
    try await run(withStdin: "", status: 1, output: "b1/tool\nb2/onlyb2\n", error: "", args: "tool", "nosuch", "onlyb2", env: ["PATH": "b1:b2"], cd: FilePath(fixtures.root))
  }
}
